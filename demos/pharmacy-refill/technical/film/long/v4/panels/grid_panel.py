"""grid_panel.py — film v4's closing panel (I9): Sentry's own verdict on each of the take's five sessions (the call to
the demand forecaster in each), and the take's counts, all read from <take>/counts.json (v4/counts4.py). Writes
<take>/panels/grid.html (panels.js screenshots it)."""
from __future__ import annotations

import json
import pathlib

import sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
from env import TAKE  # noqa: E402
C = json.loads((TAKE / "counts.json").read_text())
ROWS = [("A", "Level 1 · the full record", "Rosa’s refill · report-dispense"),
        ("B", "Level 2 · only the number", "Rosa’s refill · report-dispense"),
        ("N1", "Level 3 · the nightly batch", "its own session, after level 2 · export-dispense-batch"),
        ("C", "The fixed app", "Rosa’s refill · report-dispense"),
        ("N2", "The fixed app · the nightly batch", "its own session · export-dispense-batch")]


def row(k: str, what: str, sub: str) -> str:
    r = C["runs"][k]; block = r["enforcement"] == "block"; allow = r["level"] == "none" and r["enforcement"] == "allow"
    verdict = (f"{r['level']} · recommends block" if block else "none · allowed" if allow
               else f"{r['level']} · {r['enforcement']}")          # anything else is shown as Sentry has it, never as "allowed"
    rules = " · ".join(r["rules"]) if r["rules"] else "no rule fires"
    return (f'<div class="row" id="r-{k}"><div><b>{what}</b><i>{sub}</i></div><div class="t">trace {r["trace"][:8]}…</div>'
            f'<div class="v {"green" if allow else "red"}">{verdict}<small>{rules}</small></div></div>')


html = f"""<!doctype html>
<!-- generated by v4/panels/grid_panel.py from v4/counts.json; edit the generator -->
<html><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=Archivo:wght@800&family=Source+Sans+3:wght@600;700&family=JetBrains+Mono:wght@500;700&display=block" rel="stylesheet">
<style>
:root{{--bg:#0f1214;--panel:#171b1f;--line:#2a3036;--ink:#e9e6dc;--muted:#9aa1a8;--red:#ef5b47;--green:#5fd38a;--gold:#e5c268}}
html,body{{margin:0;width:1920px;height:1080px;overflow:hidden;background:var(--bg);color:var(--ink);font-family:'Source Sans 3',sans-serif}}
h1{{position:absolute;left:110px;top:60px;margin:0;font:800 46px Archivo,sans-serif}}h1 small{{display:block;font:600 24px 'Source Sans 3';color:var(--muted);margin-top:8px}}
#grid{{position:absolute;left:110px;top:210px;width:1700px}}
.row{{display:grid;grid-template-columns:1fr 260px 470px;align-items:center;gap:24px;background:var(--panel);border:2px solid var(--line);border-radius:14px;padding:20px 28px;margin-bottom:16px}}
.row b{{display:block;font:800 29px Archivo,sans-serif}}.row i{{display:block;font-style:normal;font:600 20px 'Source Sans 3';color:var(--muted);margin-top:4px}}
.t{{font:500 20px 'JetBrains Mono',monospace;color:var(--muted)}}
.v{{font:800 28px Archivo,sans-serif;text-align:right}}.v small{{display:block;font:600 18px 'JetBrains Mono',monospace;color:var(--muted);margin-top:4px}}
.red{{color:var(--red)}}.green{{color:var(--green)}}
#counts{{position:absolute;left:110px;top:930px;font:700 30px 'Source Sans 3';color:var(--ink)}}#counts span{{color:var(--gold)}}
</style></head><body>
<h1>Sentry’s own verdicts<small>one run on rossoctl · the call to the demand forecaster in each session</small></h1>
<div id="grid">{"".join(row(*r) for r in ROWS)}</div>
<div id="counts"><span>{C["S"]}</span> sessions · <span>{C["J"]}</span> exchanges judged · <span>{C["F"]}</span> flagged</div>
</body></html>
"""
(TAKE / "panels").mkdir(exist_ok=True); (TAKE / "panels" / "grid.html").write_text(html)
print("grid.html")
