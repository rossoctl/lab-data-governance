"""opa_panel.py <label> … — film v4's OPA panel for each captured exchange (v4/opa/<label>.json, from v4/opa_input.sh):
the request flow of the exact input Sentry sent OPA, abridged only by dropping fields (offsets, ids, the response flow),
never by rewording a value, beside OPA's answer. Writes v4/panels/opa-<label>.html (panels.js screenshots it).

    python3 v4/panels/opa_panel.py A B N1
"""
from __future__ import annotations

import html
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
from env import TAKE  # noqa: E402
OPA = TAKE / "opa"
STYLE = """:root{--bg:#0f1214;--panel:#171b1f;--line:#2a3036;--ink:#e9e6dc;--muted:#9aa1a8;--red:#ef5b47;--green:#5fd38a;--gold:#e5c268;--blue:#7aa2e8}
html,body{margin:0;width:1920px;height:1080px;overflow:hidden;background:var(--bg);color:var(--ink);font-family:'Source Sans 3',sans-serif}
h1{position:absolute;left:70px;top:40px;margin:0;font:800 40px Archivo,sans-serif}h1 small{display:block;font:600 21px 'Source Sans 3';color:var(--muted);margin-top:6px}
.card{position:absolute;background:var(--panel);border:2px solid var(--line);border-radius:14px;padding:22px 28px}
.cap{font:700 15px 'JetBrains Mono',monospace;letter-spacing:.2em;color:var(--muted);margin-bottom:12px}
.j{font:500 19.5px/1.55 'JetBrains Mono',monospace;color:#d9d5c9;white-space:pre;font-variant-ligatures:none}
.j .k{color:var(--blue)}.j .s{color:#9fd39b}.j .c{color:#7d868e;font-style:italic}.j .hot{color:#ffb4a8;font-weight:700}
.blk{display:inline-block;border-radius:8px;padding:2px 8px;margin:0 -8px}
.ans .row{display:flex;justify-content:space-between;align-items:baseline;border-top:1px solid var(--line);padding:14px 0}
.ans .row b{font:600 20px 'JetBrains Mono',monospace;color:var(--muted)}.ans .row span{font:800 30px/1.15 Archivo,sans-serif;text-align:right}
.red{color:var(--red)}.green{color:var(--green)}"""
TAGS = {"PII", "PHI", "RESTRICTED", "UNTRUSTED_EXTERNAL", "external"}


def s(v: str) -> str:
    cls = "s hot" if v in TAGS else "s"
    return f'<span class="{cls}">"{html.escape(v)}"</span>'


def k(name: str) -> str:
    return f'<span class="k">"{name}"</span>'


def item(d: dict, note: str, ident: str, tail: str = "") -> str:
    es = [f'{e["entity_type"]} {s(e["text"])}' for e in d["entities"]]
    ents = ",\n              ".join(", ".join(es[i:i + 3]) for i in range(0, len(es), 3))
    lines = [f'<span class="c">// {note}</span>',
             f'{{{k("entities")}: [{ents}],',
             f' {k("regulatory_tags")}: [{", ".join(s(t) for t in d["regulatory_tags"])}],',
             f' {k("classification_level")}: {s(d["classification_level"])}}}{tail}']
    return f'<span class="blk" id="{ident}">' + "\n".join("      " + l for l in lines) + "</span>"


def page(label: str) -> str:
    d = json.loads((OPA / f"{label}.json").read_text())
    req, res = d["input"]["flows"]["request"], d["result"]
    dest = req["data_destinations"][0]
    items = req["data_items"]
    found = item(items[0], "found here: the classifier, on this payload", "i-found", ",")
    carried = item(items[1], "carried in: data lineage, from earlier exchanges", "i-carried") if len(items) > 1 else \
        '<span class="blk c" id="i-carried">      // nothing carried in</span>'
    body = "\n".join([
        f'{{{k("flows")}: {{{k("request")}: {{',
        f'<span class="blk" id="i-event">   {k("event_type")}: {s(req["event_type"])},</span>',
        f'   {k("data_items")}: [', found, carried, "   ],",
        f'<span class="blk" id="i-dest">   {k("data_destinations")}: [{{{k("data_destination_name")}: {s(dest["data_destination_name"])},',
        f'      {k("data_destination_categories")}: [{", ".join(s(c) for c in dest["data_destination_categories"])}],',
        f'      {k("data_destination_trust_level")}: {s(dest.get("data_destination_trust_level", "UNKNOWN"))}}}]</span>',
        f'}}, {k("response")}: {{ … }}}}}}'])
    tone = "red" if res["enforcement_type"] == "block" else "green"
    rules = "<br>".join(r for r in res["triggered_rules"] if r != "0000") or "none"
    src, dst = req["data_sources"][0]["data_source_name"], dest["data_destination_name"]
    return f"""<!doctype html>
<!-- generated by v4/panels/opa_panel.py from v4/opa/{label}.json (interaction {d["interaction_id"]}); edit the generator -->
<html><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=Archivo:wght@800&family=Source+Sans+3:wght@600&family=JetBrains+Mono:wght@500;600;700&display=block" rel="stylesheet">
<style>{STYLE}</style></head><body>
<h1>What Sentry asks OPA<small>{html.escape(src)} → {html.escape(dst)} · the exact input, fields abridged</small></h1>
<div class="card" id="input" style="left:70px;top:160px;width:1240px"><div class="cap">INPUT · POST /v1/data/data_governance/policy_decision</div>
<div class="j">{body}</div></div>
<div class="card ans" id="answer" style="left:1390px;top:160px;width:400px"><div class="cap">OPA’S ANSWER</div>
<div class="row" id="ans-rules"><b>triggered_rules</b><span>{rules}</span></div>
<div class="row" id="ans-level"><b>risk_level</b><span class="{tone}">{res["risk_level"]}</span></div>
<div class="row" id="ans-enf"><b>enforcement_type</b><span class="{tone}">{res["enforcement_type"]}</span></div>
<div class="row"><b>combining</b><span style="font-size:22px">{res.get("rule_combining_mode", "")}</span></div></div>
</body></html>
"""


for label in sys.argv[1:]:
    (TAKE / "panels").mkdir(exist_ok=True); (TAKE / "panels" / f"opa-{label}.html").write_text(page(label))
    print(f"opa-{label}.html")
